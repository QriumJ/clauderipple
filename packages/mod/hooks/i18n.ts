/** Localize diagnostic labels, not model ids, enum values, or model-written reasons. */
export function debugText(lang: Lang, value: unknown): string {
  return JSON.stringify(value, (_key, entry: unknown) => {
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) return entry
    return Object.fromEntries(Object.entries(entry).map(([key, item]) => [
      Object.hasOwn(DEBUG_KEYS, key) ? t(lang, DEBUG_KEYS[key]!) : key, item,
    ]))
  }, 2)
}

export function t(lang: Lang, key: string, vars?: Readonly<Record<string, string | number>>): string {
  const table: Readonly<Record<string, string>> = STRINGS[lang] ?? STRINGS.en
  const english: Readonly<Record<string, string>> = STRINGS.en
  const text = Object.hasOwn(table, key) ? table[key] : undefined
  const fallback = Object.hasOwn(english, key) ? english[key] : undefined
  return (text ?? fallback ?? key).replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    vars && Object.hasOwn(vars, name) ? String(vars[name]) : placeholder)
}

const NAMES: Readonly<Record<string, Lang>> = {
  korean: 'ko', '한국어': 'ko', english: 'en', chinese: 'zh', '简体中文': 'zh', '中文': 'zh',
  japanese: 'ja', '日本語': 'ja', spanish: 'es', 'español': 'es', portuguese: 'pt', 'português': 'pt',
}

export function langFrom(value: string | undefined): Lang | undefined {
  if (!value) return undefined
  const normalized = value.trim().toLowerCase()
  if (Object.hasOwn(NAMES, normalized)) return NAMES[normalized]
  const base = normalized.split(/[-_.@]/)[0]
  return base === 'ko' || base === 'en' || base === 'zh' || base === 'ja' || base === 'es' || base === 'pt' ? base : undefined
}
